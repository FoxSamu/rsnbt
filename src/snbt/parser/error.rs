use std::fmt::Debug;
use std::fmt::Display;
use std::fmt::Formatter;
use std::result::Result as StdResult;

use super::lex::TokenKind;
use crate::tag::TagId;

/// An SNBT syntax error.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum SyntaxError {
    /// The end of file was found while parsing a token.
    UnexpectedEof,

    /// An unexpected character was found while parsing a token.
    ///
    /// # Parameters
    /// - the unexpected character.
    UnexpectedCharacter(char),

    /// An incomplete escape sequence was found in a string.
    IncompleteEscapeSequence,

    /// An invalid code point was found in a string escape.
    /// E.g. `\U00110000` will cause this error.
    ///
    /// # Parameters
    /// - The invalid codepoint value.
    InvalidCodepoint(u32),

    /// An invalid code point name was found in a string escape.
    /// E.g. `\N{This is most definitely not a unicode character}` will cause this error.
    ///
    /// # Parameters
    /// - The unrecognized code point name.
    NoSuchCodepoint(String),

    /// An unpaired surrogate character was found in a string.
    ///
    /// # Parameters
    /// - The dangling surrogate character.
    DanglingSurrogate(u16),

    /// One out of a specific set of tokens was expected, but something else was found.
    ///
    /// # Parameters
    /// - A list of expected token kinds;
    /// - a boolean indicating whether the end of file is expected here;
    /// - the found token kinds, or `None` if the end of file was found.
    ExpectedToken(Vec<TokenKind>, bool, Option<TokenKind>),

    /// A malformed numeric value was found.
    ///
    /// # Parameters
    /// - The malformed numeral as a string.
    MalformedNumeral(String),

    /// An unrecognised array prefix was found.
    ///
    /// # Parameters
    /// - The array type that was found.
    InvalidArrayType(String),

    /// Two elements of distinct types were found in the a list literal.
    ///
    /// # Parameters
    /// - The expected tag type of the list's elements (based off the first tag in the list);
    /// - the type of the mismatched tag.
    DisallowedHetrogenousList(TagId, TagId),
}

/// An SNBT parsing error. An error can happen for 3 reasons:
/// - there is a [syntax error][SyntaxError];
/// - the size limit was exceeded (input cannot exceed [`usize::MAX`] characters);
/// - there was an I/O error, the type of which depends on what errors the input produces.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum ParseError<E> {
    Syntax(u64, SyntaxError),
    SizeLimit,
    Io(E),
}

/// An SNBT parsing result. This is either `T` or a [`ParseError`].
///
/// The error type parameter, `E`, specifies the error type generated by the underlying I/O
/// mechanism. It is wrapped in [`ParseError`] and may be [`Infallible`].
pub type ParseResult<T, E> = StdResult<T, ParseError<E>>;



// ============================================================================================

impl Display for SyntaxError {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self {
            SyntaxError::UnexpectedEof => {
                write!(f, "unexpected end of file")
            },
            SyntaxError::UnexpectedCharacter(c) => {
                write!(f, "unexpected character '{}'", c)
            },
            SyntaxError::IncompleteEscapeSequence => {
                write!(f, "incomplete escape sequence")
            },
            SyntaxError::InvalidCodepoint(c) => {
                write!(f, "invalid codepoint 0x{:X}", c)
            },
            SyntaxError::NoSuchCodepoint(c) => {
                write!(f, "no codepoint named '{}'", c)
            },
            SyntaxError::ExpectedToken(t, end, got) => {
                write!(f, "expected ")?;
                let mut iter = t.iter();

                let Some(first) = iter.next() else {
                    return if *end {
                        write!(f, "end")
                    } else {
                        write!(f, "nothing")
                    };
                };

                write!(f, "{}", first)?;

                for elem in iter {
                    write!(f, ", {}", elem)?;
                }

                if *end {
                    write!(f, ", end")?;
                }

                if let Some(kind) = got {
                    write!(f, ", got {}", kind)?;
                } else {
                    write!(f, ", got end")?;
                }

                Ok(())
            },
            SyntaxError::MalformedNumeral(c) => {
                write!(f, "malformed numeral '{}'", c)
            },
            SyntaxError::InvalidArrayType(c) => {
                write!(f, "invalid array type '{}'", c)
            },
            SyntaxError::DisallowedHetrogenousList(expected, got) => {
                write!(f, "tags of different types in list, expected {}, got {}", expected, got)
            },
            SyntaxError::DanglingSurrogate(c) => {
                write!(f, "dangling surrogate \\u{:4X}", c)
            },
        }
    }
}

impl<E> Display for ParseError<E>
where
    E: Display,
{
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self {
            ParseError::Syntax(index, err) => write!(f, "syntax error at {}: {}", index, err),
            ParseError::SizeLimit => write!(f, "size limit of {} characters exceeded", u64::MAX),
            ParseError::Io(err) => write!(f, "io error: {}", err),
        }
    }
}
